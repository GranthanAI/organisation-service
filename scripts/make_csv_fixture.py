"""Write tests/fixtures/college_2000.csv: a 2,000-row student list with 50 bad rows of mixed reasons, so an upload gives
1,950 invites and 50 errors. Deterministic (no randomness), so the committed file can be regenerated byte for byte.

    uv run python -m scripts.make_csv_fixture [path]

The 50 bad rows: 20 invalid emails, 15 duplicates of earlier rows, 10 blank-email rows, 5 with a role that is not allowed.
Some names contain commas, quotes and accents, and a few start with = or + (the file must survive a spreadsheet).
"""

import csv
import sys
from pathlib import Path

ROWS, BAD = 2000, 50
DEFAULT = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "college_2000.csv"
NAMES = ["Asha Verma", "Ravi Kumar", "José Álvarez", 'Meera "Mimi" Rao', "Singh, Harpreet", "=Ankit Sharma", "+Priya Nair", "Zoë Patel"]


def build() -> list[list[str]]:
    rows: list[list[str]] = []
    good = 0
    for i in range(ROWS):
        name = NAMES[i % len(NAMES)]
        if i % 40 == 7:
            kind = ("invalid", "duplicate", "blank", "role")[(i // 40) % 4]
        else:
            kind = "good"
        if kind == "good":
            rows.append([f"student{good:04d}@amity.edu", name, "member"])
            good += 1
        elif kind == "invalid":
            rows.append([f"not-an-email-{i}", name, "member"])
        elif kind == "duplicate":
            rows.append([f"STUDENT{max(good - 3, 0):04d}@Amity.edu", name, "member"])
        elif kind == "blank":
            rows.append(["", name, "member"])
        else:
            rows.append([f"student{good:04d}@amity.edu", name, "owner"])
            good += 1
    return rows


def main(path: Path = DEFAULT) -> None:
    rows = build()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.writer(f, lineterminator="\r\n")
        writer.writerow(["email", "name", "role"])
        writer.writerows(rows)
    print(f"wrote {path} ({len(rows)} rows)")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT)
